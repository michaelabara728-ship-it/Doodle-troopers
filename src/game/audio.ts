  private playNoise(duration: number, volume: number, filterFreq: number) {
    if (!this.ctx) return;
    const bufferSize = Math.floor(this.ctx.sampleRate * duration);
    const buffer = this.ctx.createBuffer(1, bufferSize, this.ctx.sampleRate);
    const data = buffer.getChannelData(0);
    for (let i = 0; i < bufferSize; i++) {
      data[i] = Math.random() * 2 - 1;
    }

    const noise = this.ctx.createBufferSource();
    noise.buffer = buffer;

    const filter = this.ctx.createBiquadFilter();
    filter.type = 'lowpass';
    filter.frequency.setValueAtTime(filterFreq, this.ctx.currentTime);
    filter.frequency.exponentialRampToValueAtTime(100, this.ctx.currentTime + duration);

    const gain = this.ctx.createGain();
    gain.gain.setValueAtTime(volume, this.ctx.currentTime);
    gain.gain.exponentialRampToValueAtTime(0.001, this.ctx.currentTime + duration);

    noise.connect(filter);
    filter.connect(gain);
    gain.connect(this.ctx.destination);
    noise.start();
  }

  public setJetpack(active: boolean) {
    if (this.isMuted) {
      if (this.jetpackGain && this.ctx) this.jetpackGain.gain.setValueAtTime(0, this.ctx.currentTime);
      return;
    }
    this.initContext();
    if (!this.ctx) return;

    if (active) {
      if (!this.isJetpackPlaying) {
        this.isJetpackPlaying = true;
        const bufferSize = this.ctx.sampleRate * 2;
        const buffer = this.ctx.createBuffer(1, bufferSize, this.ctx.sampleRate);
        const data = buffer.getChannelData(0);
        for (let i = 0; i < bufferSize; i++) {
          data[i] = (Math.random() * 2 - 1) * 0.5;
        }

        const noise = this.ctx.createBufferSource();
        noise.buffer = buffer;
        noise.loop = true;

        const filter = this.ctx.createBiquadFilter();
        filter.type = 'bandpass';
        filter.frequency.setValueAtTime(550, this.ctx.currentTime);
        filter.Q.setValueAtTime(2.5, this.ctx.currentTime);

        this.jetpackGain = this.ctx.createGain();
        this.jetpackGain.gain.setValueAtTime(0.18, this.ctx.currentTime);

        noise.connect(filter);
        filter.connect(this.jetpackGain);
        this.jetpackGain.connect(this.ctx.destination);
        noise.start();
      } else if (this.jetpackGain) {
        this.jetpackGain.gain.setValueAtTime(0.18, this.ctx.currentTime);
      }
    } else {
      if (this.jetpackGain) {
        this.jetpackGain.gain.setValueAtTime(0, this.ctx.currentTime);
      }
    }
  }

